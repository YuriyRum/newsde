export type TranslationKey = keyof typeof UI_TRANSLATIONS['de'];

export function t(key: TranslationKey, lang: AppLanguage, params?: Record<string, string | number>): string {
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['de'];
  let text = dict[key] || UI_TRANSLATIONS['de'][key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}

